  public static async convertAllNecessary(songs: Song[]) {
    songs = songs.filter(s => StorageSelector.isLocal(s));
    if (songs.length > 0 && toxenapi.isDesktop()) {
      // Check if needs conversion

      const globalId = Toxen.notify({
        title: "Converting all necessary",
        content: `0% complete`,
      });

      async function convertSong(song: Song) {
        if (!toxenapi.isDesktop()) { toxenapi.throwDesktopOnly(); }
        const id = Toxen.notify({
          title: "Converting " + song.getDisplayName() + " to MP3",
          content: `0% complete`
        });
        await toxenapi.ffmpeg.convertToMp3(song, (progress) => {
          updateNotification({
            id,
            title: "Converting " + song.getDisplayName() + " to MP3",
            message: <div>
              {Math.round(progress.percent)}% complete
              <br />
              {progress.timemark}
            </div>,
            autoClose: false,
          });
        });

        updateNotification({
          id,
          title: "Converting " + song.getDisplayName() + " to MP3",
          message: <div>
            100% complete
          </div>,
          autoClose: 500,
        });

        updateNotification({
          id: globalId,
          title: "Converting all necessary",
          message: <div>
            {Math.round((songs.indexOf(song) / songs.length) * 100)}% complete
          </div>,
          color: "green",
          autoClose: false
        });
      }

      const convertable = Toxen.getTranscodeAudioFiles();
      songs = songs.filter(s => !s.usesProvider() && convertable.includes(toxenapi.getFileExtension(s.mediaFile()).toLowerCase()))

      // Convert 3 at a time
      let i = 0;
      let active = 0;
      while (i < songs.length) {
        const song = songs[i];
        if (active < 3) {
          i++;
          active++;
          convertSong(song)
            .catch(error => Toxen.error(`Failed to convert "${song.getDisplayName()}": ${error?.message ?? error}`))
            .finally(() => {
              active--;
            });
        }
        if (active >= 3) await new Promise(r => setTimeout(r, 1000));
      }

      while (active > 0) await new Promise(r => setTimeout(r, 1000));

      updateNotification({
        id: globalId,
        title: "Converting all necessary",
        message: <div>
          100% complete
          <br />
          {i} / {songs.length}
        </div>,
        color: "green",
        autoClose: 2000,
      });

      return songs.length;
    }
  }

