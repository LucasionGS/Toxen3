  /**
   * Re-read this song's info from its local `info.json`. Does nothing for songs that aren't stored locally.
   */
  public async reload() {
    if (!StorageSelector.isLocal(this)) {
      return;
    }

    const data: Partial<ISong> = await this.storage.readText(this, SongStorage.INFO_FILE).then(text => text && JSON.parse(text)).catch((): null => null);
    if (data) copyInfoKeys(this, data);

    return this;
  }

  /**
   * Save the song's info through its storage. Local saves are picked up by the sync engine on their own.
   */
  public async saveInfo(): Promise<void> {
    this.hash = Song.randomFileHash();
    const curSong = Song.getCurrent();
    if (curSong === this) {
      curSong.setAppTitle();
    }

    try {
      await this.storage.saveInfo(this);
    } catch (error) {
      console.error(error);
      Toxen.notify({
        title: "Failed to save Song",
        content: this.getDisplayName(),
        expiresIn: 5000,
        type: "error"
      });
    }
  }

