/**
 * Copy the keys of `SONG_INFO_KEYS` that exist in `from` onto `to`.
 * The `Missing` default is a compile-time check: it stops compiling when `SONG_INFO_KEYS` lacks an `ISong` field.
 */
function copyInfoKeys<Missing extends never = Exclude<keyof ISong, (typeof SONG_INFO_KEYS)[number]>>(to: ISong, from: Partial<ISong>): void {
  const copy = <K extends keyof ISong>(key: K) => { to[key] = from[key] as ISong[K]; };
  for (const key of SONG_INFO_KEYS) {
    if (key in from) copy(key);
  }
}

