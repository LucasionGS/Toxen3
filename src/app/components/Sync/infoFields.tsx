import React from "react";
import { Tooltip } from "@mantine/core";
import { Toxen } from "../../ToxenApp";
import "./infoFields.scss";

/**
 * Labels for song info fields, matching the Edit Song panel. Keys that aren't here are humanised from their name.
 */
const FIELD_LABELS: Record<string, string> = {
  coArtists: "Co-artists",
  url: "URL",
  year: "Release year",
  subtitleDelay: "Subtitle offset",
  visualizerPulseBackground: "Background pulsing",
  visualizerForceRainbowMode: "Force rainbow mode",
  rainfallImage: "Rainfall custom image",
  rainfallImageScale: "Rainfall image scale",
  autogeneratedTheme: "Autogenerated theme",
  "paths.media": "Media file",
  "paths.background": "Background file",
  "paths.subtitles": "Subtitle file",
  "paths.storyboard": "Storyboard file",
  "paths.dirname": "Song folder",
};

/**
 * Longest string shown in a table cell before it is cut off and moved to a tooltip.
 */
const MAX_TEXT_LENGTH = 60;

/**
 * "floatingTitleOutlineColor" -> "Floating title outline color".
 */
export function humanizeKey(key: string): string {
  const words = key.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[_-]+/g, " ").trim().toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

function findPlaylistName(id: string): string | null {
  const playlist = Toxen.playlists?.find(p => p.id === id || p.name === id);
  return playlist?.name ?? null;
}

/**
 * Readable name of a field. `playlistSettings.<id>.<key>` becomes "In playlist 'Name': Key" when the playlist exists.
 */
export function getFieldLabel(field: string): string {
  const direct = FIELD_LABELS[field];
  if (direct) return direct;

  const [root, second, ...rest] = field.split(".");
  if (root === "playlistSettings" && second !== undefined) {
    const name = findPlaylistName(second);
    const scope = name ? `In playlist '${name}'` : "In a playlist";
    return rest.length === 0 ? scope : `${scope}: ${getFieldLabel(rest.join("."))}`;
  }
  if (second !== undefined) return `${getFieldLabel(root)}: ${getFieldLabel([second, ...rest].join("."))}`;
  return humanizeKey(root);
}

//#region Values

const PULSE_LABELS: Record<string, string> = { "pulse": "Always pulse", "pulse-off": "Never pulse" };

function isColorKey(key: string): boolean {
  return /colou?r$/i.test(key);
}

function isRgbArray(value: unknown): value is number[] {
  return Array.isArray(value) && (value.length === 3 || value.length === 4) && value.every(n => typeof n === "number" && n >= 0 && n <= 255);
}

function toHex(rgb: number[]): string {
  return `#${rgb.slice(0, 3).map(n => Math.round(n).toString(16).padStart(2, "0")).join("")}`;
}

/**
 * The CSS color and hex text for a color value (`#rrggbb` string or `[r, g, b]` array), or `null` if it isn't one.
 */
function parseColor(value: unknown): { css: string; text: string } | null {
  if (isRgbArray(value)) return { css: toHex(value), text: toHex(value) };
  if (typeof value === "string" && /^#([0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i.test(value.trim())) {
    return { css: value.trim(), text: value.trim().toLowerCase() };
  }
  return null;
}

/**
 * Plain text for a value of a field, or `null` when it needs a richer rendering (colors).
 */
function formatText(key: string, value: unknown): string {
  if (value === null) return "Follow global setting";
  if (typeof value === "boolean") return value ? "On" : "Off";
  if (typeof value === "number") {
    if (key === "backgroundDim") return `${value}%`;
    if (key === "subtitleDelay") return `${value} ms`;
    return String(value);
  }
  if (typeof value === "string") {
    if (value === "") return "Empty";
    return PULSE_LABELS[value] ?? value;
  }
  if (Array.isArray(value)) {
    return value.length === 0 ? "Empty" : value.map(item => typeof item === "object" && item !== null ? JSON.stringify(item) : formatText(key, item)).join(", ");
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return "Empty";
    return entries.map(([k, v]) => `${getFieldLabel(k)}: ${parseColor(v)?.text ?? formatText(k, v)}`).join(", ");
  }
  return String(value);
}

export interface InfoValueProps {
  /** Dotted field name, used to pick the right formatting. */
  field: string;
  value: unknown;
  /** `false` when the field doesn't exist on that side, which is not the same as `null`. */
  present: boolean;
}

/**
 * A field value the way a user would read it: swatches for colors, On/Off for booleans, "Follow global setting" for
 * `null`, and a tooltip with the full text when it's cut off.
 */
export function InfoValue(props: InfoValueProps) {
  const { field, value, present } = props;
  if (!present) return <span className="info-value info-value--muted">not set</span>;

  const key = field.split(".").pop() ?? field;
  const color = (isColorKey(key) || isRgbArray(value)) ? parseColor(value) : null;
  if (color) {
    return (
      <span className="info-value">
        <span className="info-value__swatch" style={{ background: color.css }} />
        <code>{color.text}</code>
      </span>
    );
  }

  const text = formatText(key, value);
  const muted = value === null || text === "Empty";
  if (text.length <= MAX_TEXT_LENGTH) return <span className={`info-value${muted ? " info-value--muted" : ""}`}>{text}</span>;
  return (
    <Tooltip label={text} multiline maw={360} withinPortal>
      <span className="info-value">{`${text.slice(0, MAX_TEXT_LENGTH)}…`}</span>
    </Tooltip>
  );
}

